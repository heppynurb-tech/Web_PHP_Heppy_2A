<?php
// Operator Penugasan
// Operator berikutnya yang harus kamu ketahi adalah operator penugasan atau assignment. Operator ini adalah operator untuk memberikan tugas kepada variabel biasanya digunakan untuk mengisi nilai.

$kecepatan = 83;
 
// ini opertor aritmatika
$kecepatan = $kecepatan + 10;
 
// maka nilai kecepatan akan sama dengan 83 + 10 = 93
 
// ini operator penugasan
$kecepatan += 10;
 
// sekarang nilai kecepatan akan menjadi 93 + 10 = 103
 
echo "nilai kecepatan adalah $kecepatan";
 
?>